#!/usr/bin/env python3
"""Report which Bitwig Controller API methods the extension already calls.

Lists every public method of every interface in com.bitwig.extension.controller.api (via javap on
the extension-api jar Gradle downloaded) and marks a method "used" when its name is called anywhere
in src/main/java. Name matching is approximate (overloads and same-named methods on other interfaces
count as used), so treat it as a map of what is untouched, not a proof of coverage.

usage: python3 scripts/api_coverage.py [--markdown]   (run from the repo root after ./gradlew build)
"""
import glob
import os
import re
import subprocess
import sys

# Interfaces that drive physical controllers, USB/OSC devices or the extension's own UI settings.
# They have no use for an MCP agent and are reported separately.
HARDWARE = re.compile(
    r"^(Hardware|Absolute|Relative|Continuous|MultiState|OnOff|InternalHardware|Usb|Midi(In|Out)|NoteInput|"
    r"RemoteSocket|RemoteConnection|Osc|Pipe|InputPipe|OutputPipe|Boolean|Color|Integer|Object|String)"
    r".*(Hardware|Binding|Matcher|Light|Display|Surface|Control|Pipe|Property|Bindable|Knob|Slider|Button|Element|"
    r"Interface|Transfer|Socket|Connection|Expressions|Latch|Input)?$"
)
HARDWARE_EXTRA = {"PianoKeyboard", "UsbDevice", "MidiExpressions", "NoteLatch", "Signal", "Setting", "Settings",
                  "Preferences", "DocumentState", "NotificationSettings", "HardwareDevice", "AudioHardwareIoInfo",
                  "AudioIoDeviceMatcher", "MasterRecorder"}


def api_jar():
    jars = glob.glob(os.path.expanduser("~/.gradle/caches/modules-2/files-2.1/com.bitwig/extension-api/*/*/*.jar"))
    jars = [j for j in jars if not j.endswith("-sources.jar") and not j.endswith("-javadoc.jar")]
    if not jars:
        sys.exit("extension-api jar not found; run ./gradlew build first")
    return sorted(jars)[-1]


def api_methods(jar):
    names = subprocess.run(["unzip", "-Z1", jar], capture_output=True, text=True, check=True).stdout.split()
    classes = sorted(n[:-6].replace("/", ".") for n in names
                     if n.startswith("com/bitwig/extension/controller/api/") and n.endswith(".class") and "$" not in n)
    out = subprocess.run(["javap", "-cp", jar, *classes], capture_output=True, text=True, check=True).stdout
    api, current = {}, None
    for line in out.splitlines():
        m = re.match(r"public (?:interface|abstract class|class|final class) com\.bitwig\.extension\.controller\.api\.(\w+)", line)
        if m:
            current = m.group(1)
            api[current] = []
            continue
        m = re.match(r"\s+public (?:abstract |default |static )*[\w.<>\[\], ?]+ (\w+)\((.*)\);", line)
        if m and current and m.group(1) not in ("values", "valueOf"):
            api[current].append(f"{m.group(1)}({m.group(2).replace('java.lang.', '').replace('com.bitwig.extension.controller.api.', '').replace('com.bitwig.extension.callback.', '')})")
    return api


def used_names(root="src/main/java"):
    names = set()
    for path in glob.glob(f"{root}/**/*.java", recursive=True):
        names.update(re.findall(r"\.(\w+)\(", open(path, encoding="utf-8").read()))
    return names


def main():
    api = api_methods(api_jar())
    used = used_names()
    rows = []
    for iface, methods in sorted(api.items()):
        hw = bool(HARDWARE.match(iface)) and iface not in ("Channel", "ChannelBank") or iface in HARDWARE_EXTRA
        done = [m for m in methods if m.split("(")[0] in used]
        todo = [m for m in methods if m.split("(")[0] not in used]
        rows.append((iface, hw, done, todo))
    total = sum(len(d) + len(t) for i, hw, d, t in rows if not hw)
    covered = sum(len(d) for i, hw, d, t in rows if not hw)
    print(f"# Bitwig Controller API coverage\n")
    print(f"Agent-relevant interfaces: {covered} of {total} methods referenced by name "
          f"({100 * covered // max(total, 1)}%). Generated by `scripts/api_coverage.py`.\n")
    print("| Interface | Used | Not yet used |\n|---|---|---|")
    for iface, hw, done, todo in rows:
        if hw or not (done or todo):
            continue
        print(f"| `{iface}` | {len(done)} | {', '.join('`' + t.split('(')[0] + '`' for t in todo) or '—'} |")
    print("\n## Hardware, controller-surface and settings interfaces (out of scope for MCP)\n")
    print(", ".join(f"`{i}`" for i, hw, d, t in rows if hw))


if __name__ == "__main__":
    main()
